#!/usr/bin/env python3
"""Zero only formant rows no fixed PATCH record selects; retain every live i16.

The complete canonical table is src/audio/formants.rs. FORMANT's mode is the
low u16 of the immutable record mode, not a graph input. Consider ALL records,
including unreachable ones, so the proof does not depend on reachability.
"""
from audio_inputs import ROOT, CRATE, array, emit, patch_words, records


def main():
    patch = patch_words()
    coefficients = array(ROOT / 'src/audio/formants.rs', 'COEFFICIENTS')
    assert len(coefficients) == 25 * 15
    used = set()
    for at in records(patch):
        if patch[at] & 127 == 57:
            mode = patch[at + 1 + ((patch[at] >> 8) & 127)]
            assert 0 <= mode < 25, 'invalid FORMANT mode'
            used.add(mode)
    result = [value if i // 15 in used else 0 for i, value in enumerate(coefficients)]
    for mode in used:
        assert result[mode * 15:(mode + 1) * 15] == coefficients[mode * 15:(mode + 1) * 15]
    modes = ', '.join(map(str, sorted(used)))
    lines = ['// Generated by size/tools/encode_formants.py from src/audio/formants.rs and the fixed PATCH.\n',
             f'// Only rows selected by FORMANT modes {modes} are retained.\n',
             'pub const COEFFICIENTS: [i16; 375] = [\n']
    for at in range(0, len(result), 15):
        lines.append('    ' + ','.join(map(str, result[at:at + 15])) + ',\n')
    lines.append('];\n')
    emit(CRATE / 'src/audio/formants.rs', ''.join(lines))
    print(f'FORMANT modes: {modes}; {25 - len(used)} unused rows zeroed')


if __name__ == '__main__':
    main()
