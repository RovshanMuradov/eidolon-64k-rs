#!/usr/bin/env python3
"""Generate the shared encoder/decoder NASM configuration. No third-party modules.

Recovered from c15.json and gen_model.py (t15t). Model selectors: 1 = position
modulo 4 plus c0, 10 = previous high nibble plus c0, 2/7 = bytes -2/-3,
12 = 4 KiB region. The region mixer supports streams strictly below 1 MiB.
posm bits 7/6 select the word/region hashes; bits 0..5 mask the position.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
RANGES = {1: 1024, 10: 4096, 2: 256, 7: 256, 12: 256}
PARAMS = {'LR': 'lr', 'SM': 'sm', 'APMR': 'apm', 'ST': 'st', 'DP': 'dp',
          'MX': 'mx', 'RT': 'rt', 'AC': 'ac', 'RSH': 'rsh'}


def generate(cfg):
    nmodel = len(cfg['masks'])
    ninput = (2 + 4 * nmodel + 3) & ~3
    mix = cfg['mix']
    if not 1 <= nmodel <= 14 or not 3 <= 3 + len(mix) <= 8:
        raise ValueError('model exceeds the depacker disp8/MMX limits')
    for key in ('masks', 'bitm', 'posm'):
        if len(cfg[key]) != nmodel or any(type(v) is not int or not 0 <= v <= 255 for v in cfg[key]):
            raise ValueError(f'{key}: expected {nmodel} byte values')
    if any(type(v) is not int or v not in RANGES for v in mix):
        raise ValueError('unsupported mixer selector')
    for key in PARAMS.values():
        if type(cfg[key]) is not int or not 0 <= cfg[key] <= 31:
            raise ValueError(f'{key}: expected a shift/rate in 0..31')
    values = {'NMODEL': nmodel, 'NINPUT': ninput, 'NMIX': 3 + len(mix),
              'NWEIGHT': 768 + sum(RANGES[v] for v in mix), 'WK': '0x2f0b4ae5'}
    values.update((key, cfg[value]) for key, value in PARAMS.items())
    lines = ['; Generated by generate_model.py from model.json; do not edit.',
             '; Both model_asm.asm and depacker.asm include this file.']
    lines += [f'%define {key:<9} {value}' for key, value in values.items()]
    # Code 12 uses one byte for the region; encoder/decoder agree below this bound.
    lines += [f'%define MAXSTREAM {1 << 20 if 12 in mix else 0x7fffffff}', '',
              '%macro MODEL_TABLES 0']
    for key in ('masks', 'bitm', 'posm'):
        lines.append(f'{key:<14}db ' + ', '.join(f'0x{v:02x}' for v in cfg[key]))
    lines += ['%endmacro', '', '%macro ENCODER_MIX_CONTEXTS 0']
    if mix:
        lines.append('  movzx     ecx, byte [ebp+Work.c0]')
    base = 768
    for index, code in enumerate(mix):
        if code == 1:
            lines += ['  mov       eax, ebx', '  sub       eax, [_startBufPtr]',
                      '  and       eax, 3', '  shl       eax, 8',
                      f'  lea       eax, [eax+ecx+{base}]']
        elif code == 10:
            lines += ['  movzx     eax, byte [ebx-1]', '  shr       eax, 4',
                      '  shl       eax, 8', f'  lea       eax, [eax+ecx+{base}]']
        elif code in (2, 7):
            lines += [f'  movzx     eax, byte [ebx-{2 if code == 2 else 3}]',
                      f'  add       eax, {base}']
        else:
            lines += ['  mov       eax, ebx', '  sub       eax, [_startBufPtr]',
                      '  shr       eax, 12', f'  add       eax, {base}']
        lines.append(f'  mov       [ebp+Work.ctx+{4 * (3 + index)}], eax')
        base += RANGES[code]
    lines += ['%endmacro', '', '%macro DECODER_MIX_CONTEXTS 0']
    base = 768
    for code in mix:
        if code in (1, 10):
            if code == 1:
                lines += ['  mov       eax, ebx', '  sub       eax, [ebp+W_origdst]',
                          '  and       eax, 3']
            else:
                lines += ['  movzx     eax, byte [ebx-1]', '  shr       eax, 4']
            lines += [f'  add       al, {base >> 8}', '  mov       ah, al', '  mov       al, cl']
        elif code in (2, 7):
            lines += [f'  movzx     eax, byte [ebx-{2 if code == 2 else 3}]',
                      f'  mov       ah, {base >> 8}']
        else:
            lines += ['  mov       eax, ebx', '  sub       eax, [ebp+W_origdst]',
                      '  shr       eax, 12', f'  mov       ah, {base >> 8}']
        lines.append('  stosd')
        base += RANGES[code]
    lines += ['%endmacro', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the checked-in include is stale')
    args = parser.parse_args()
    target = HERE / 'model_config.inc'
    text = generate(json.loads((HERE / 'model.json').read_text()))
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('stale model_config.inc: run python3 size/packer/generate_model.py')
        print('PASS shared t15t model configuration')
    else:
        target.write_text(text)


if __name__ == '__main__':
    main()
