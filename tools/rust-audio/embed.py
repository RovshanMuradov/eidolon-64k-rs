#!/usr/bin/env python3
"""Extract only pinned score/patch and 15 PCM16 instrument waves as Rust constants."""
import hashlib
import json
import os
from pathlib import Path
import struct

def sha(data):
    return hashlib.sha256(data).hexdigest()

def main():
    data = Path(os.environ['EIDOLON_DATA'])
    pin = json.loads(Path('analysis/audio/manifest.json').read_text())
    image = (data / pin['inputs']['postfix']['path']).read_bytes()
    bank = (data / 'reference/dependencies/gm.dls').read_bytes()
    assert sha(image) == pin['inputs']['postfix']['sha256']
    assert sha(bank) == pin['inputs']['dls']['sha256']
    closure = json.loads(Path('analysis/audio/audit.json').read_text())['event_closure']['event_reachable_samples']
    waves, p = [], 0
    while p < len(bank) - 8:
        if bank[p:p+4] == b'data':
            n, = struct.unpack_from('<I', bank, p+4)
            assert n % 2 == 0 and p+8+n <= len(bank)
            waves.append(bank[p+8:p+8+n])
            p += 8+n
        p += 1
    assert len(waves) == 495 and len(closure) == 15
    assert sum(len(waves[i]) for i in closure) == 85548
    output = ['// Generated by tools/rust-audio/embed.py from hash-pinned original data.\n']
    assets = {}
    def array(name, typ, values, raw):
        output.append(f'pub static {name}: &[{typ}] = &[\n')
        for at in range(0, len(values), 24):
            output.append('    ' + ','.join(map(str, values[at:at+24])) + ',\n')
        output.append('];\n')
        assets[name] = {'bytes': len(raw), 'sha256': sha(raw)}
    for name, raw in [('SCORE', image[0x37040:0x3edcf]), ('PATCH', image[0x3edf0:0x40c30])]:
        array(name, 'u8', list(raw), raw)
    output.append('pub use super::gmdls_samples::WAVES;\n')
    data_output, output = output, ['// Generated by tools/rust-audio/embed.py from hash-pinned original data.\n'
        '// Instrument samples from the Roland GM/GS Sound Set (gm.dls), (c) 1996 Roland Corporation.\n'
        "// Not covered by this repository's license.\n"]
    for index in closure:
        raw = waves[index]
        array(f'WAVE_{index}', 'i16', list(struct.unpack('<'+'h'*(len(raw)//2), raw)), raw)
    output.append('pub static WAVES: &[(u16, &[i16])] = &[\n')
    output.extend(f'    ({i}, WAVE_{i}),\n' for i in closure)
    output.append('];\n')
    samples_path = Path('src/audio/gmdls_samples.rs')
    samples_path.write_text(''.join(output))
    output = data_output
    output.append('''/// Native bank initialization duplicates each 22050-Hz mono sample into two stereo frames.
pub fn wave(index: u16) -> Option<Vec<[f64; 2]>> {
    let raw = WAVES.iter().find(|(id, _)| *id == index)?.1;
    let mut result = Vec::with_capacity(raw.len() * 2);
    for &v in raw { let s = f64::from(v) / 32768.0; result.push([s, s]); result.push([s, s]); }
    Some(result)
}
#[no_mangle]
pub unsafe extern "C" fn eidolon_wave(index: u32, out: *mut f64, capacity: usize) -> usize {
    let Some(wave) = wave(index as u16) else { return 0; };
    if !out.is_null() && capacity >= wave.len() {
        core::ptr::copy_nonoverlapping(wave.as_ptr().cast::<f64>(), out, wave.len() * 2);
    }
    wave.len()
}
''')
    path = Path('src/audio/data.rs')
    path.write_text(''.join(output))
    manifest = {'schema': 'eidolon-rust-audio-assets-v1', 'input_image_sha256': sha(image),
                'bank_sha256': sha(bank), 'samples': closure, 'sample_pcm16_bytes': 85548,
                'assets': assets, 'generated_sha256': sha(path.read_bytes()),
                'samples_generated_sha256': sha(samples_path.read_bytes())}
    Path('artifacts/rust/audio').mkdir(parents=True, exist_ok=True)
    Path('artifacts/rust/audio/assets.json').write_text(json.dumps(manifest, indent=2)+'\n')
    print('Embedded', len(closure), 'instrument samples; 85548 PCM16 bytes; score/patch included')

if __name__ == '__main__':
    main()
