#!/usr/bin/env python3
"""Embed the complete pinned source/native-matched formant coefficient table."""
import hashlib
import json
import os
from pathlib import Path
import re
import struct
pin=json.loads(Path('analysis/audio/manifest.json').read_text())
source=Path(os.environ['EIDOLON_ROOT'])/'.tools/analysis/audio/64klang/Player/Player/SynthNode.cpp'
raw=source.read_bytes()
assert hashlib.sha256(raw).hexdigest()==pin['source']['files']['SynthNode.cpp']
body=raw.decode().split('short FORMANT_Coeff[FORMANT_NUM_COEFFS] =',1)[1].split('{',1)[1].split('}',1)[0]
body=re.sub(r'//[^\n]*','',body)
values=[int(x.strip()) for x in body.split(',') if x.strip()]
assert len(values)==375
output='// Generated by tools/rust-audio/formants.py; complete pinned 25-vowel table.\n'
output+='pub const COEFFICIENTS: [i16; 375] = [\n'
output+=''.join('    '+','.join(map(str,values[i:i+15]))+',\n' for i in range(0,375,15))+'];\n'
path=Path('src/audio/formants.rs'); path.write_text(output)
Path('artifacts/rust/audio/formants.json').write_text(json.dumps({
    'source_sha256':hashlib.sha256(raw).hexdigest(), 'entries':375,
    'table_i16le_sha256':hashlib.sha256(struct.pack('<375h',*values)).hexdigest(),
    'generated_sha256':hashlib.sha256(path.read_bytes()).hexdigest()},indent=2)+'\n')
