#!/usr/bin/env python3
"""Embed hash-pinned recovery assets; no native image or target execution needed."""
import argparse
import hashlib
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest_path = ROOT / 'analysis/graphics/assets.json'
    manifest = json.loads(manifest_path.read_bytes())
    source = Path(os.environ['EIDOLON_DATA']) / 'analysis/graphics'
    outputs = {}
    inputs = []

    def read(entry):
        data = (source / entry['path']).read_bytes()
        assert len(data) == entry['bytes'] and digest(data) == entry['sha256'], entry['path']
        inputs.append({'path': entry['path'], 'bytes': len(data), 'sha256': digest(data)})
        return data

    chunks = {}
    for chunk in manifest['chunks']:
        raw = read(chunk)
        assert b'\0' not in raw
        chunks[chunk['address']] = chunk['path']
        outputs[chunk['path']] = raw
    raw = outputs['shaders/00409918.glsl']
    assert raw.startswith(b'#version 450\n')
    outputs['shaders/00409918-effective.glsl'] = b'#version 450 compatibility\n' + raw[13:]
    for table in manifest['tables'].values():
        outputs['src/data/' + Path(table['path']).name] = read(table)
    tables = json.loads(read(manifest['decoded']))
    names = {}
    for row in tables['rows']:
        for uniform in row['uniforms']:
            index, name = uniform['name_index'], uniform['uniform']
            assert index not in names or names[index] == name
            names[index] = name

    lines = ['// Generated by tools/rust/import_assets.py; source hashes in artifacts/rust/engine/assets.json.',
             '#[rustfmt::skip]', 'pub static UNIFORM_NAMES: &[(u32, &str)] = &[']
    lines += [f'    ({index}, "{name}"),' for index, name in sorted(names.items())]
    lines += ['];', '#[rustfmt::skip]', 'pub static PROGRAM_SOURCES: &[&[&str]] = &[']
    for program in manifest['programs']:
        lines.append('    &[')
        raw_concat = b''.join(outputs[chunks[a]] for a in program['source_addresses'])
        assert digest(raw_concat) == program['concatenated_sha256']
        for address in program['source_addresses']:
            path = chunks[address]
            if program['index'] == 0 and address == '0x409918':
                path = 'shaders/00409918-effective.glsl'
            lines.append(f'        concat!(include_str!("../{path}"), "\\0"),')
        lines.append('    ],')
    loader = chunks[manifest['loading_shader']]
    lines += ['];', f'pub static LOADING_SOURCE: &str = concat!(include_str!("../{loader}"), "\\0");', '']
    outputs['src/generated.rs'] = '\n'.join(lines).encode()
    provenance = {
        'schema': 'eidolon-rust-engine-assets-v1',
        'recovery_manifest_sha256': digest(manifest_path.read_bytes()),
        'inputs': inputs,
        'outputs': [{'path': p, 'bytes': len(d), 'sha256': digest(d)} for p, d in sorted(outputs.items())],
        'effective_change': 'program0 only: #version 450\\n -> #version 450 compatibility\\n',
    }
    outputs['artifacts/rust/engine/assets.json'] = (json.dumps(provenance, indent=2) + '\n').encode()
    for path, data in outputs.items():
        target = ROOT / path
        if args.check:
            assert target.read_bytes() == data, path
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
    print(f'EMBEDDED_ASSETS_VERIFIED files={len(outputs)} shader_chunks={len(chunks)} rows={len(tables["rows"])}')


if __name__ == '__main__':
    main()
